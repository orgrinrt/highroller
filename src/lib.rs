// `RUID` holds an integer, or a `OnceLock` around one, and both are already `Send` and
// `Sync`, so the compiler establishes this on its own. It used to be asserted with two
// `unsafe impl`s behind an `async` feature. They were not needed, and an `unsafe impl`
// that is not needed is worse than none, because it would go on asserting the property
// after a change that stopped it being true.
//
// The `async` feature is kept so that naming it is not an error, and gates nothing.
#[cfg(feature = "ruid_type")]
const _: () = {
    const fn require<T: Send + Sync>() {}
    require::<RUID<Rolled>>();
    require::<RUID<Derived>>();
};

